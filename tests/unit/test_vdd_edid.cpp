namespace {
  std::string
  generate_hex(unsigned int w, unsigned int h, unsigned int fps, bool hdr, const std::string &name) {
    const auto edid = vdd_edid::generate_virtual_display_edid(w, h, fps, hdr, name);
    std::string out;
    for (auto byte : edid) {
      char buf[6];
      std::snprintf(buf, sizeof(buf), "0x%02X,", byte);
      out += buf;
    }
    return out;
  }

  int
  block_checksum(const std::vector<std::uint8_t> &edid, std::size_t start, std::size_t end) {
    int sum = 0;
    for (std::size_t i = start; i < end; ++i) {
      sum += edid[i];
    }
    return sum % 256;
  }
}  // namespace

