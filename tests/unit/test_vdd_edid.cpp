TEST(VddEdid, MatchesReference1080p60Hdr) {
  const auto edid = vdd_edid::generate_virtual_display_edid(1920, 1080, 60, true, "Foundation VDD");

  ASSERT_EQ(edid.size(), 256u);
  EXPECT_EQ(generate_hex(1920, 1080, 60, true, "Foundation VDD"), std::string(REFERENCE_1080P60_HDR_BASE) + REFERENCE_1080P60_HDR_CEA);
}

TEST(VddEdid, ChecksumsAreValidForCommonModes) {
  const unsigned int modes[][3] = {
    { 1920, 1080, 60 },
    { 1920, 1080, 120 },
    { 2560, 1440, 120 },
    { 2560, 1440, 165 },
    { 3840, 2160, 60 },
    { 1280, 720, 90 },
  };

  for (const auto &mode : modes) {
    for (bool hdr : { false, true }) {
      const auto edid = vdd_edid::generate_virtual_display_edid(mode[0], mode[1], mode[2], hdr, "Foundation VDD");
      EXPECT_EQ(block_checksum(edid, 0, 128), 0) << mode[0] << 'x' << mode[1] << '@' << mode[2] << " base block";
      EXPECT_EQ(block_checksum(edid, 128, 256), 0) << mode[0] << 'x' << mode[1] << '@' << mode[2] << " cea block";
    }
  }
}

TEST(VddEdid, PreferredTimingMatchesRequestedMode) {
  const auto edid = vdd_edid::generate_virtual_display_edid(2560, 1440, 120, false, "Foundation VDD");

  const auto pixel_clock = static_cast<std::uint16_t>(edid[54] | (edid[55] << 8));
  const unsigned int h_active = edid[56] | ((edid[58] >> 4) << 8);
  const unsigned int h_blank = edid[57] | ((edid[58] & 0x0F) << 8);
  const unsigned int v_active = edid[59] | ((edid[61] >> 4) << 8);

  EXPECT_EQ(h_active, 2560u);
  EXPECT_EQ(v_active, 1440u);

  const unsigned int h_total = h_active + h_blank;
  // The generator clamps v_blank in a second pass from the first-pass clock.
  const unsigned int v_blank = std::max(23u, static_cast<unsigned int>(1440 * 0.025));
  const auto expected_clock = static_cast<std::uint16_t>(static_cast<unsigned int>(h_total * (1440 + v_blank) * 120) / 10000);
  EXPECT_EQ(pixel_clock, expected_clock);
}

TEST(VddEdid, HdrBlockPresenceFollowsFlag) {
  const auto with_hdr = vdd_edid::generate_virtual_display_edid(1920, 1080, 60, true, "VDD");
  const auto without_hdr = vdd_edid::generate_virtual_display_edid(1920, 1080, 60, false, "VDD");

  // HDR Static Metadata Data Block (0xE6, 0x06) right after colorimetry
  EXPECT_EQ(with_hdr[136], 0xE6);
  EXPECT_EQ(with_hdr[137], 0x06);
  // Without HDR the first data block is the Video Capability DB (0xE2, 0x00)
  EXPECT_EQ(without_hdr[132], 0xE2);
  EXPECT_EQ(without_hdr[133], 0x00);
}

