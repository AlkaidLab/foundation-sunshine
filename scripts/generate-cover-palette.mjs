#!/usr/bin/env node
// Writes src/generated_cover_palette.h: the Material 3 (HCT) colours of the generated covers for every hue, so the host draws exactly the colours of the cover design
// without carrying the colour-science code. A colour of a cover is hct(chroma, tone) at the hue of the application name (plus an offset for the accent colours).
//
//   node scripts/generate-cover-palette.mjs [path-to-material-color-utilities]
//
// The package is @material/material-color-utilities (Apache-2.0, Google): Hct.from(hue, chroma, tone).toInt(). See docs/authority/source-index.tsv.
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const folder = process.argv[2] || process.env.MATERIAL_COLOR_UTILITIES
// only the colour model is needed: the package's root module pulls in the whole library (dynamic colour, schemes), which some Node versions cannot resolve.
// A folder given on the command line is turned into a file URL (also a drive path of Windows); without one the installed package is found by its public entry (the only path its
// exports table names) and the colour model is read from the folder beside it.
const hctUrl = folder ? pathToFileURL(join(resolve(folder), 'hct/hct.js')) : new URL('hct/hct.js', import.meta.resolve('@material/material-color-utilities'))
const { Hct } = await import(hctUrl.href)

// [chroma, tone] pairs used by the styles (tonal, monogram, editorial, glass, geometric)
const SPECS = [
  [52, 38], [40, 22], [60, 56], [30, 90], [50, 22], [4, 98], [60, 82],
  [12, 94], [34, 86], [60, 34], [24, 16],
  [10, 94], [8, 10], [34, 82], [40, 66], [56, 90],
  [40, 24], [70, 66], [66, 62], [62, 56],
  [64, 62], [56, 66], [44, 82], [12, 95], [40, 28],
]
const rows = SPECS.map(([c, t]) => {
  const values = []
  for (let hue = 0; hue < 360; hue++) values.push('0x' + (Hct.from(hue, c, t).toInt() & 0xffffff).toString(16).padStart(6, '0'))
  return values
})
const names = SPECS.map(([c, t]) => `C${c}T${t}`)
let out = `// Generated by scripts/generate-cover-palette.mjs from @material/material-color-utilities (Apache-2.0); do not edit.
// kHct[spec][hue] is the sRGB colour (0xRRGGBB) of Hct(hue, chroma, tone) for the (chroma, tone) pair the name of the spec says.
#pragma once

#include <array>
#include <cstdint>

namespace generated_cover::palette {

  enum spec_e : int {
    ${names.map((n, i) => `${n} = ${i}`).join(',\n    ')},
    kSpecCount
  };

  inline constexpr std::array<std::array<std::uint32_t, 360>, kSpecCount> kHct { {
`
for (const row of rows) {
  out += '    { {\n'
  for (let i = 0; i < 360; i += 12) out += '      ' + row.slice(i, i + 12).join(', ') + ',\n'
  out += '    } },\n'
}
out += `  } };

  /// the colour of a spec at a hue in degrees (any integer; offsets such as hue + 55 wrap around)
  constexpr std::uint32_t
  hct(spec_e spec, int hue) {
    return kHct[spec][((hue % 360) + 360) % 360];
  }

}  // namespace generated_cover::palette
`
writeFileSync(join(root, 'src/generated_cover_palette.h'), out)
console.log(`${SPECS.length} specs x 360 hues`)
