#include "MatDumpFile.h"
#include "recording_receiver.h"
#include "../../third-party/moonlight-common-c/src/MatWire.h"
#include <openssl/evp.h>
#include <stdio.h>
#include <stdlib.h>
static int failures,consumed,completed;
#define CHECK(x) do{if(!(x)){fprintf(stderr,"line %d: %s\n",__LINE__,#x);++failures;}}while(0)
static int consume(void* c,const MAT_CYCLE_INFO* i,const uint8_t* p,size_t n){(void)c;(void)i;(void)p;(void)n;++consumed;return 1;}
static int complete(void* c,uint64_t count){(void)c;CHECK(count==1);++completed;return 1;}
static int exists(const char* path){FILE* file=fopen(path,"rb");if(!file)return 0;fclose(file);return 1;}
int main(int argc,char** argv) {
    if(argc!=2)return 2;
    uint8_t carrier[MAT_WIRE_CYCLE]={0},packet[MAT_WIRE_PACKET],digest[32];unsigned length=0;char hash[65];
    memcpy(carrier,"\x72\xf8\x1f\x4e\x16\x00\x02\x00",8);
    CHECK(EVP_Digest(carrier,sizeof(carrier),digest,&length,EVP_sha256(),NULL)==1&&length==32);
    for(unsigned i=0;i<32;i++)snprintf(hash+i*2,3,"%02x",digest[i]);
    LI_MAT_DUMP_PROFILE expected;CHECK(MatProfileSet(&expected,hash,"1"));
    for(int test=0;test<7;test++) {
        char path[2048],partial[2064];snprintf(path,sizeof(path),"%s/case%d.raw",argv[1],test);snprintf(partial,sizeof(partial),"%s.partial",path);
        LI_MAT_DUMP_PROFILE profile=expected;if(test==3)profile.sha256[0]='0';if(test==4)profile.cycles=2;
        MAT_DUMP_FILE* dump=MatDumpOpen(path,&profile);CHECK(dump!=NULL);if(!dump)return 1;
        if(test==6) {
            LI_MAT_PLAYBACK_CALLBACKS cb=MatDumpCallbacks(dump);
            CHECK(cb.cycle(cb.context,carrier,sizeof(carrier),1,1,0,0));CHECK(cb.end(cb.context,1));
        } else {
            for(unsigned i=0;i<MAT_WIRE_FRAGMENTS;i++) {
                mat_wire_make(packet,MAT_WIRE_DATA,1,1,0,i,mat_hash(carrier,sizeof(carrier)),carrier);
                if(test==1&&i==20)continue;
                if(test==2&&i==20)packet[100]^=1;
                MatDumpPush(dump,packet,sizeof(packet));
            }
            mat_wire_make(packet,MAT_WIRE_END,1,1,1,0,mat_hash(carrier,sizeof(carrier)),NULL);
            if(test!=5)MatDumpPush(dump,packet,sizeof(packet));
        }
        int success=test==0||test==6;CHECK(MatDumpPublished(dump)==success);MatDumpClose(dump);
        CHECK(exists(path)==success);CHECK(exists(partial)==!success);
        if(success)CHECK(MatDumpOpen(path,&profile)==NULL);
    }
    for(int test=0;test<6;test++) {
        MAT_RECORDING_RECEIVER receiver;MatRecordingInit(&receiver,consume,complete,NULL);consumed=completed=0;
        MAT_CYCLE_INFO info={1,1,0,0};
        if(test==1)info.index=1;if(test==2)info.pts48k=1;
        int result=MatRecordingPush(&receiver,&info,carrier,test==3?61439:61440);
        if(test>=1&&test<=3){CHECK(result<0&&consumed==0);CHECK(MatRecordingEnd(&receiver,1)<0);continue;}
        CHECK(result==1&&consumed==1);
        if(test==4)CHECK(MatRecordingPush(&receiver,&info,carrier,sizeof(carrier))<0);
        CHECK((MatRecordingEnd(&receiver,test==5?2:1)==2)==(test==0));
        CHECK(completed==(test==0));
    }
    MAT_RECORDING_RECEIVER empty;MatRecordingInit(&empty,consume,complete,NULL);CHECK(MatRecordingEnd(&empty,0)<0);
    if(failures)return 1;
    puts("PASS tool-owned dump publication: 7 cases; independent raw-recording input: 7 cases; generated bytes, no native/hardware");return 0;
}
